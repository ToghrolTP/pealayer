import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {ACTIONS,actionIndex,browserActions,defaultLayout,moveAction,orderedActions,patchAction} from '../src/controlBars.ts';
const source = (path) => readFileSync(new URL(path,import.meta.url),'utf8');
const rust = source('../../src/config.rs');
const nativeIds = rust.match(/pub enum ControlBarAction\s*\{([^}]+)\}/)[1].split(',').map((s)=>s.trim()).filter(Boolean)
  .map((s)=>s.replace(/[A-Z]/g,(c,i)=>`${i?'_':''}${c.toLowerCase()}`));
assert.deepEqual(ACTIONS,nativeIds,'flag indexes and persisted semantic identities match Rust');
assert.equal(ACTIONS.length,15);
assert.deepEqual(defaultLayout('simple').order.slice(0,3),['back','play_pause','forward']);
assert.equal(defaultLayout('monitor').hidden[actionIndex('stop')],false);
assert.equal(defaultLayout('simple').hidden[actionIndex('stop')],true);
assert.equal(browserActions.includes('pin'),false,'browser does not claim a native floating window');
const original = defaultLayout('monitor');
const hidden = patchAction(original,'stop','hidden',true);
const moved = moveAction(hidden,'stop','mute',true);
assert.equal(moved.end[actionIndex('stop')],true);
assert.equal(moved.hidden[actionIndex('stop')],true,'reorder does not reveal hidden actions');
assert.equal(new Set(moved.order).size,ACTIONS.length);
assert.deepEqual(original,defaultLayout('monitor'),'editing clones rather than mutating authoritative state');
assert.equal(moveAction(moved,'stop','stop',true),moved);
assert.equal(orderedActions(['mute','mute']).length,ACTIONS.length);
const bar=source('../src/components/ControlBar.tsx'),app=source('../src/App.tsx'),css=source('../src/styles.css');
assert(bar.includes("trigger={['contextMenu']}")&&bar.includes("trigger={['click','contextMenu']}"),'every action and the always-present overflow has a menu');
assert(bar.includes("setDragImage(event.currentTarget,event.clientX-rect.left,event.clientY-rect.top)"),'drag preserves the original grab offset');
assert(bar.includes("event.key==='Escape'")&&bar.includes('suppressClick.current=true'),'cancel and release cannot execute a dragged action');
assert(bar.includes("patchAction(layout,drag.current,'hidden',true)")&&bar.includes('is-removing'),'trash drop hides the semantic action');
assert(bar.includes('draggable={!saving&&Boolean(authoritative)}')&&bar.includes('disabled={!enabled(a)}'),'unavailable actions customize independently of execution');
assert(app.includes("expected:{control_bars:current.control_bars}, values:{control_bars:next}"),'save is narrow and optimistic-concurrency checked');
assert(css.includes('.control-bar__action.is-dragging { visibility: hidden; }'),'drag image does not duplicate a decorated original');
assert(css.includes('.control-bar__overflow { display: inline-flex; flex: none; }'),'restore/trash does not scroll away with actions');
assert(source('../src/components/StudioTab.tsx').includes('<ControlBar')&&source('../src/components/RemoteControlTab.tsx').includes('<ControlBar'),'both Web workspaces reuse the component');
console.log('Control bars: semantic IDs, order/visibility/sides, immutable edits and shared integration passed.');
