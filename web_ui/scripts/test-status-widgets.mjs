import assert from 'node:assert/strict';
import { selectedWorkspace } from '../src/workspaces.ts';
import { tr } from '../src/i18n.ts';
import { DEFAULT_VISIBILITY, WIDGETS, orderedWidgets, displayedWidgets, reorderWidgets, widgetVisible, setWidgetVisible, nextFpsMode, screenRateSelected, numericTelemetry, appendSample, chartPaths } from '../src/statusWidgets.ts';
assert.equal(DEFAULT_VISIBILITY.chart, false);
assert.equal(tr('fa', 'Switch workspace'), 'تغییر فضای کاری');
assert.equal(tr('fa', 'Workspace'), 'فضای کاری');
const workspaceProfiles = [{ id: 'simple', name: 'Watch films', icon: 'video', order: 0, mode: 'simple' },
  { id: 'authoring', name: 'My authoring desk', icon: 'effects', order: 1, mode: 'nle' }];
assert.equal(selectedWorkspace(workspaceProfiles, 'simple')?.name, 'Watch films');
assert.equal(selectedWorkspace(workspaceProfiles, 'authoring')?.icon, 'effects');
assert.equal(selectedWorkspace(workspaceProfiles, 'Watch films'), undefined, 'captions never become stable IDs');
assert.equal(selectedWorkspace(undefined, 'simple'), undefined, 'no invented disconnected profile');
assert.equal(displayedWidgets(['workspace', 'temperature', 'fps']).at(-1), 'workspace');
assert.deepEqual(reorderWidgets([...WIDGETS], 'workspace', 'fps', false), [...WIDGETS]);
assert.equal(DEFAULT_VISIBILITY.fps_mode, 'auto');
assert.deepEqual(['media', 'ui', 'auto'].map(nextFpsMode), ['ui', 'auto', 'media']);
assert.equal(screenRateSelected('auto', true, true), false);
assert.equal(screenRateSelected('auto', false, true), true);
assert.equal(screenRateSelected('auto', true, false), true);
assert.deepEqual(orderedWidgets(['temperature', 'temperature', 'unknown']).slice(0, 2), ['temperature', 'fps']);
assert.equal(orderedWidgets(['temperature']).length, WIDGETS.length);
const reordered = reorderWidgets([...WIDGETS], 'temperature', 'fps', false);
assert.equal(reordered[0], 'temperature');
assert.equal(new Set(reordered).size, WIDGETS.length);
assert.deepEqual(reorderWidgets([...WIDGETS], 'fps', 'fps', true), [...WIDGETS]);
const hidden = setWidgetVisible(DEFAULT_VISIBILITY, 'voltage', false);
assert.equal(widgetVisible(hidden, 'voltage'), false);
assert.equal(widgetVisible(hidden, 'current'), true);
assert.equal(widgetVisible(setWidgetVisible(hidden, 'connection', false), 'current'), true);
assert.equal(numericTelemetry(null), undefined);
assert.equal(numericTelemetry(false), undefined);
assert.equal(numericTelemetry(0), 0);
assert.equal(numericTelemetry(NaN), undefined);
let samples = [];
for (let i = 0; i < 300; i++) samples = appendSample(samples, { time: i * 500, values: [i, undefined, undefined] });
assert.equal(samples.length, 240);
assert.equal(appendSample(samples, { time: 149501, values: [0] }).length, 240);
const paths = chartPaths([{ time: 0, values: [1] }, { time: 500, values: [undefined] }, { time: 1000, values: [2] }], 0, 100, 20);
assert.equal(paths.length, 2, 'missing samples break the line, never become zero');
assert.deepEqual(chartPaths([{ time: 0, values: [undefined] }], 0, 100, 20), []);
console.log('Status widgets: FPS modes, order, visibility, bounded logging and unavailable data checks passed.');
