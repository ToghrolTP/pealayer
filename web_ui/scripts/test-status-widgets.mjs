import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { selectedWorkspace } from '../src/workspaces.ts';
import { tr } from '../src/i18n.ts';
import { DEFAULT_VISIBILITY, WIDGETS, orderedWidgets, displayedWidgets, widgetVisible, setWidgetVisible, reorderWidgets, nextFpsMode, screenRateSelected, numericTelemetry, appendSample, chartPaths, operationTone, operationDestination } from '../src/statusWidgets.ts';
assert.equal(DEFAULT_VISIBILITY.chart, false);
assert.equal(tr('fa', 'Switch workspace'), 'تغییر فضای کاری');
assert.equal(tr('fa', 'Workspace'), 'فضای کاری');
const workspaceProfiles = [{ id: 'simple', name: 'Watch films', icon: 'video', order: 0, mode: 'simple' },
  { id: 'authoring', name: 'My authoring desk', icon: 'effects', order: 1, mode: 'nle' }];
assert.equal(selectedWorkspace(workspaceProfiles, 'simple')?.name, 'Watch films');
assert.equal(selectedWorkspace(workspaceProfiles, 'authoring')?.icon, 'effects');
assert.equal(selectedWorkspace(workspaceProfiles, 'Watch films'), undefined, 'captions never become stable IDs');
assert.equal(selectedWorkspace(undefined, 'simple'), undefined, 'no invented disconnected profile');
assert.equal(displayedWidgets(['workspace', 'temperature', 'fps']).at(-1), 'workspace');
assert.equal(reorderWidgets([...WIDGETS], 'workspace', 'fps', false)[0], 'workspace');
assert.equal(DEFAULT_VISIBILITY.trailing[WIDGETS.indexOf('workspace')], true);
assert.equal(DEFAULT_VISIBILITY.trailing[WIDGETS.indexOf('voltage')], false);
assert.equal(DEFAULT_VISIBILITY.monospace[WIDGETS.indexOf('current')], true);
assert.deepEqual(DEFAULT_VISIBILITY.metric_limits, [[null,null],[null,null],[null,null]]);
assert.equal(DEFAULT_VISIBILITY.fps_mode, 'auto');
assert.deepEqual(['media', 'ui', 'auto'].map(nextFpsMode), ['ui', 'auto', 'media']);
assert.equal(screenRateSelected('auto', true, true), false);
assert.equal(screenRateSelected('auto', false, true), true);
assert.equal(screenRateSelected('auto', true, false), true);
assert.deepEqual(orderedWidgets(['temperature', 'temperature', 'unknown']).slice(0, 2), ['temperature', 'fps']);
assert.equal(orderedWidgets(['temperature']).length, WIDGETS.length);
const reordered = reorderWidgets([...WIDGETS], 'temperature', 'fps', false);
assert.equal(reordered[0], 'temperature');
assert.equal(new Set(reordered).size, WIDGETS.length);
assert.deepEqual(reorderWidgets([...WIDGETS], 'fps', 'fps', true), [...WIDGETS]);
const hidden = setWidgetVisible(DEFAULT_VISIBILITY, 'voltage', false);
assert.equal(widgetVisible(hidden, 'voltage'), false);
assert.equal(widgetVisible(hidden, 'current'), true);
assert.equal(widgetVisible(setWidgetVisible(hidden, 'connection', false), 'current'), true);
assert.equal(numericTelemetry(null), undefined);
assert.equal(numericTelemetry(false), undefined);
assert.equal(numericTelemetry(0), 0);
assert.equal(numericTelemetry(NaN), undefined);
assert.equal(operationTone('controller-host'), 'host');
assert.equal(operationTone('controller-board'), 'board');
assert.equal(operationTone('controller-transfer'), 'transfer');
assert.equal(operationTone('app'), 'app');
assert.equal(operationDestination('controller-host'), 'hardware');
assert.equal(operationDestination('controller-board'), 'hardware');
assert.equal(operationDestination('download'), 'downloads');
assert.equal(operationDestination('app'), 'preferences');
assert.equal(tr('fa', 'PCController update'), 'به‌روزرسانی PCController');
let samples = [];
for (let i = 0; i < 300; i++) samples = appendSample(samples, { time: i * 500, values: [i, undefined, undefined] });
assert.equal(samples.length, 240);
assert.equal(appendSample(samples, { time: 149501, values: [0] }).length, 240);
const paths = chartPaths([{ time: 0, values: [1] }, { time: 500, values: [undefined] }, { time: 1000, values: [2] }], 0, 100, 20);
assert.equal(paths.length, 2, 'missing samples break the line, never become zero');
assert.deepEqual(chartPaths([{ time: 0, values: [undefined] }], 0, 100, 20), []);
const styles = readFileSync(new URL('../src/styles.css', import.meta.url), 'utf8');
const view = readFileSync(new URL('../src/components/ApplicationStatusBar.tsx', import.meta.url), 'utf8');
assert.ok(view.includes("screenRate ? ' is-screen-rate' : ''"));
assert.match(styles,/\.status-widget--fps, \.status-widget--fps \.app-statusbar__fps\s*\{\s*font-weight:\s*400;/,'FPS must be regular for media, render and Auto modes');
const connectionRule = styles.match(/\.app-statusbar \.status-widget--connection\s*\{([^}]+)\}/)?.[1] ?? '';
assert.match(connectionRule, /width:\s*max-content/, 'connection caption must use spare bar space');
assert.match(connectionRule, /flex:\s*0 1 auto/, 'caption may shrink on narrow screens');
assert.match(styles, /\.status-connection-caption\s*\{[^}]*min-width:\s*0[^}]*text-overflow:\s*ellipsis/);
assert.match(view, /className="status-connection-caption"/);
assert.doesNotMatch(view, /\{width:\s*252\}/, 'showing transport must not restore a fixed width ceiling');
const dividerRule = styles.match(/\.status-widget-divider\s*\{([^}]+)\}/)?.[1] ?? '';
assert.match(dividerRule, /flex:\s*0 0 1px/);
assert.match(dividerRule, /height:\s*12px/);
assert.match(dividerRule, /align-self:\s*center/);
assert.match(dividerRule, /background:\s*var\(--line\)/);
assert.match(dividerRule, /pointer-events:\s*none/);
assert.doesNotMatch(styles, /\.status-widget\s*\+\s*\.status-widget\s*\{[^}]*border/,
  'a full-height widget border steals text width and does not match the native inset separator');
assert.match(view, /\.map\(widgetElement\)\.filter\(\(element\)=>element!==null\)/,
  'only rendered widgets participate in divider placement');
assert.match(view, /config\.dividers && index>0 && <span className="status-widget-divider" aria-hidden="true"/,
  'no divider before the first visible item in either group');
